import '../security/cryptex.dart';

// ─── tracker_info ───────────────────────────────────────────
// Masked AppsFlyer + Firebase identifiers.
// All values resolve lazily through Cryptex.
// ────────────────────────────────────────────────────────────

const List<int> _trackerKeyMask = <int>[
  0x05, 0x28, 0x9f, 0x10, 0xa7, 0x51, 0xc8, 0x22,
  0x1b, 0x2c, 0x1c, 0x21, 0xd0, 0x2a, 0x6b, 0xef,
  0xe4, 0x29, 0xaf, 0xad, 0x25, 0xe9,
];

const List<int> _projectNumberMask = <int>[
  0x4c, 0x42, 0xe9, 0x7c, 0xe5, 0x12, 0x88, 0x71,
  0x11, 0x66, 0x4c, 0x57,
];

const List<int> _gcdHostMask = <int>[
  0x17, 0x05, 0xae, 0x3a, 0xa7, 0x1e, 0x91, 0x68,
  0x45, 0x37, 0x1d, 0x15, 0xfa, 0x14, 0x2d, 0xcf,
  0xf0, 0x3d, 0xbd, 0x8e, 0x7b, 0xc4, 0x8e, 0x8c,
  0x51, 0x12, 0xb5, 0x27,
];

const List<int> _gcdPathMask = <int>[
  0x50, 0x18, 0xb4, 0x39, 0xa0, 0x45, 0xd2, 0x2b,
  0x7d, 0x30, 0x18, 0x12, 0xff, 0x50, 0x75, 0x9a,
  0xae, 0x7d, 0xe1,
];

String unwrapTrackerKey() => unmask(_trackerKeyMask);

String unwrapProjectNumber() => unmask(_projectNumberMask);

/// Build the GCD endpoint for an "Organic" attribution retry.
String buildGcdEndpoint({required String appId, required String deviceId}) {
  final base = unmask(_gcdHostMask) + unmask(_gcdPathMask);
  return '$base$appId?device_id=$deviceId';
}
